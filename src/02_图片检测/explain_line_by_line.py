# ============================================================
# 第 1 部分：导入
# ============================================================

from ultralytics import YOLO
# from ... import ... 的意思是：从 ultralytics 这个"工具箱"里，
# 拿出 YOLO 这个"工具"来用。
# 类比：从工具箱里拿出一把锤子。

# ============================================================
# 第 2 部分：变量
# ============================================================

model = YOLO("models/yolov8m.pt")
# 等号 = 是"赋值"：把右边的东西，装进左边这个名字里。
# 右边：用 YOLO 这个工具，加载名为 "yolov8m.pt" 的文件。
# 左边：装进一个叫 model 的盒子里。
# 之后说 model 就是指这个加载好的模型。

# ============================================================
# 第 3 部分：函数调用
# ============================================================

results = model("data/test1.jpg")
# model 后面加括号 = "让模型干活"
# 括号里的 "data/test1.jpg" 是"喂给它的东西"（参数）
# 干完的活，结果装进 results 这个盒子

# ============================================================
# 第 4 部分：列表和索引
# ============================================================

r = results[0]
# results 是个"列表"（list）—— 一排盒子，编号从 0 开始
# results[0] 是"取出第 0 个盒子"，也就是第 1 张图的结果
# 为什么有列表？因为可以一次喂多张图，结果就成一排了

# ============================================================
# 第 5 部分：for 循环 —— 这是最难的，慢慢看
# ============================================================

count = 0
# 建一个计数器，初始值 0

for box in r.boxes:
# for ... in ... 是"循环"：把后面的东西一个一个拿出来，每次装进前面的名字
# 翻译成人话：
#   r.boxes 里有几个检测框，就循环几次
#   每次循环，把当前这个框装进 box 这个名字里
#
#   第 1 次循环：box = 第 1 个框
#   第 2 次循环：box = 第 2 个框
#   ...
#
# 【重要】for 循环的行末尾一定要有冒号 :
# 【重要】下一行必须缩进（4 个空格），表示"这些是被循环执行的"

    cls_id = int(box.cls)
    # 取出这个框的类别编号
    # box.cls 拿到的是 tensor([0.]) 这种张量（浮点数）
    # int(...) 把它转成整数 0，才能当索引查表用

    name = model.names[cls_id]
    # model.names 是一本"字典"：{0: 'person', 1: 'bicycle', ...}
    # 用方括号 + 编号，就能取出对应的名字
    # cls_id 是 0，就取出 'person'

    if name == "person":
    # if ... : 是"条件判断"
    # == 是"判断相等"（一个等号是赋值，两个等号才是比较）
    # 翻译：如果这个名字等于 "person"，就执行下面缩进的代码

        count = count + 1
        # 计数器加 1
        # 也可以写成 count += 1，意思一样

    # 这里没缩进，说明循环继续，处理下一个框

# ============================================================
# 第 6 部分：打印结果
# ============================================================

print(f"图里有 {count} 个人")
# print(...) 是"打印到屏幕"
# f"..." 是"格式化字符串"—— 可以在文字里插入变量的值
# {count} 会被替换成 count 的实际数字
# 比如 count 是 2，就打印：图里有 2 个人

