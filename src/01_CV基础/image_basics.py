# ============================================
# OpenCV 基础：图片到底是什么
# ============================================

import cv2

# ---------- 1. 读图 ----------
# cv2.imread() 把图片读成一张"数字表格"
# 读不到文件时不会报错，直接返回 None（坑！）
img = cv2.imread("data/images/bus.png")

# 保险做法：检查有没有读成功
if img is None:
    print("图片没读到！检查路径")
    exit()          # 直接退出，不往下跑


# ---------- 2. 看这张表格的形状 ----------
# shape 返回 3 个数：(高, 宽, 通道数)
# 高 315 = 有 315 行，宽 474 = 有 474 列
# 3 = 每个格子存 3 个数（蓝、绿、红）
print("形状:", img.shape)

# dtype 是每个数字的类型
# uint8 = 无符号 8 位整数，范围 0~255，占 1 个字节
print("类型:", img.dtype)


# ---------- 3. 取单个像素 ----------
# img[行, 列] 取一个格子
# 注意：第一个数是行（从上往下数），第二个是列（从左往右数）
# 返回 3 个数，顺序是 蓝、绿、红（BGR，不是 RGB！）
print("左上角 img[0,0]:", img[0, 0])

# 取图片正中间（高 315，宽 474，所以中间大约在第 157 行、237 列）
print("中心 img[157,237]:", img[157, 237])


# ---------- 4. 只取一个通道 ----------
# 加第三个数就是选通道：0=蓝 1=绿 2=红
# img[行, 列, 通道] = 一个数
print("中心的蓝色值:", img[157, 237, 0])


# ---------- 5. 切一块区域（切片） ----------
# 语法 img[起始行:结束行, 起始列:结束列]
# 注意：结束位置不包含在内（左闭右开）
# img[100:105, 200:205] 取 第100~104行、第200~204列 → 5×5 的方块
# 最后加个 0 表示只取蓝色通道
block = img[100:105, 200:205, 0]
print("5x5 蓝色方块:")
print(block)
print("这块的形状:", block.shape)     # 应该是 (5, 5)


# ---------- 6. 改一个像素的值 ----------
# 表格里的数字是可以直接改的
# 把第 0 行第 0 列改成纯蓝（BGR 顺序，所以第一个数 255）
img[0, 0] = [255, 0, 0]
print("改完后左上角:", img[0, 0])


# ---------- 7. 缩放 ----------
# cv2.resize(图, (新宽, 新高))
# 注意：这里是 (宽, 高)，跟 shape 的顺序 (高, 宽) 反着来！坑！
# 原图 474x315，按比例缩小到 200 宽 → 高 = 315 * 200 / 474 ≈ 133
small = cv2.resize(img, (200, 133))
print("缩放后形状:", small.shape)     # (133, 200, 3)


# ---------- 8. 保存 ----------
# cv2.imwrite(保存的文件名, 要保存的图)
# 成功返回 True，失败返回 False
ok = cv2.imwrite("output/small.png", small)
print("保存成功?", ok)


# ---------- 9. 裁剪 ----------
# 裁剪就是从表格里切一块出来
# 取 第 50~150 行、第 100~300 列
crop = img[50:150, 100:300]
print("裁剪后形状:", crop.shape)      # (100, 200, 3)
cv2.imwrite("output/crop.png", crop)#写图函数


# ---------- 10. 转灰度图 ----------
# 把 3 个通道压成 1 个通道
# 灰度 = 0.299*R + 0.587*G + 0.114*B（人眼对绿色最敏感）
gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
print("灰度图形状:", gray.shape)       # (315, 474) —— 没有第 3 个数了！
print("灰度图左上角:", gray[0, 0])     # 只有一个数
cv2.imwrite("output/gray.png", gray)


# ============================================
# 核心认知
# ============================================
# 图片 = 一张巨大的数字表格
#   shape (高, 宽, 通道)   ← 注意顺序，高在前面
#   彩色图 3 通道，顺序 BGR（不是 RGB）
#   灰度图 1 通道
#
# 坐标系：img[行, 列]
#   行 = y 轴，从上往下增长
#   列 = x 轴，从左往右增长
#   YOLO 给的坐标 (x, y) 就是 (列, 行)，跟这里正好反着！
#
# 所有"图像处理" = 对这张表格做数学运算
# ============================================
